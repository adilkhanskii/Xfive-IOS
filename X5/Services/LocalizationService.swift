import Foundation
import SwiftUI

enum AppLanguage: String, CaseIterable, Identifiable {
    case ru, en, kk

    var id: String { rawValue }

    var label: String {
        switch self {
        case .ru: return "Русский"
        case .en: return "English"
        case .kk: return "Қазақша"
        }
    }

    var flag: String {
        switch self {
        case .ru: return "🇷🇺"
        case .en: return "🇺🇸"
        case .kk: return "🇰🇿"
        }
    }
}

@MainActor
final class LocalizationService: ObservableObject {
    static let shared = LocalizationService()
    private static let languageOverrideKey = "x5.language"

    @Published private(set) var current: AppLanguage

    init() {
        // Read the user's REAL preferred language from iOS Settings — NOT Locale.current,
        // which depends on which languages the app advertises. preferredLanguages.first
        // returns e.g. "ru-KZ" / "kk-Cyrl-KZ" / "en-US" regardless of app localizations.
        self.current = Self.resolve()

        // React to system locale changes mid-session.
        NotificationCenter.default.addObserver(
            forName: NSLocale.currentLocaleDidChangeNotification,
            object: nil,
            queue: .main
        ) { [weak self] _ in
            Task { @MainActor in self?.refreshFromSystem() }
        }
    }

    private static func resolve() -> AppLanguage {
        if let saved = UserDefaults.standard.string(forKey: languageOverrideKey),
           let language = AppLanguage(rawValue: saved) {
            return language
        }

        let raw = Locale.preferredLanguages.first ?? "en"
        let code = raw.split(separator: "-").first.map(String.init)?.lowercased() ?? "en"
        switch code {
        case "ru": return .ru
        case "kk", "kz": return .kk
        default: return .en
        }
    }

    private func refreshFromSystem() {
        guard UserDefaults.standard.string(forKey: Self.languageOverrideKey) == nil else { return }
        let next = Self.resolve()
        if next != current { current = next }
    }

    func setLanguage(_ language: AppLanguage) {
        UserDefaults.standard.set(language.rawValue, forKey: Self.languageOverrideKey)
        if current != language { current = language }
    }

    func t(_ key: String) -> String {
        Self.dict[current]?[key] ?? Self.dict[.en]?[key] ?? key
    }
}

